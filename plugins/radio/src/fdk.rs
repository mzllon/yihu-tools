//! libfdk-aac 解码器（dlopen 运行时加载）。
//!
//! 为什么选 fdk：电台直播流实测是 HE-AAC v1（AAC-LC 核心 22050Hz + SBR
//! 输出 44100Hz，见 docs/电台引擎去GStreamer化.md），纯 Rust 的 symphonia
//! 只支持到 AAC-LC、不解 SBR。为什么 dlopen 而非 -sys crate：构建期零
//! 依赖，缺库时给出安装提示而不是链接失败。
//!
//! 关键坑（2026-10-19 实测）：Ubuntu 的 libfdk-aac2 来自 `fdk-aac-free`
//! 源码包，**SBR/PS 解码器因专利授权被整体剥除**（nm 查不到任何
//! sbrDecoder 符号）——它能解 LC 核心（22050Hz 出声）但静默丢弃 SBR，
//! 音质发闷。因此加载策略不是「有库就行」：
//! 1. 优先插件自带的完整版（`scripts/build-fdk-aac.sh` 从 fdk-aac 上游
//!    源码构建，随插件装在 `lib/` 下，绝对路径加载）；
//! 2. 系统库作为回退，但必须通过 [`PROBE_FRAMES`] 真帧解码探针
//!    （解出 44100Hz 才算 SBR 可用），free 版会被拒；
//! 3. 全部候选不合格才报错，错误文案区分「缺库」与「free 版无 SBR」。
//!
//! 签名与枚举值对拍 fdk-aac-sys 0.5 预生成绑定（fdk-aac 2.0.2 ABI，
//! 该解码 API 自 2016 年起未变）。

use std::ffi::CString;
use std::path::PathBuf;
use std::sync::Arc;

use yihu_core::pwarn;

/// TRANSPORT_TYPE.TT_MP4_ADTS（fdk-aac-sys bindings.rs：ADTS=2，不是 0）。
const TT_MP4_ADTS: i32 = 2;
/// AAC_DEC_OK。
const AAC_DEC_OK: u32 = 0;
/// 帧长上限（INT_PCM 数）：HE-AAC 帧长 2048 × 最多 8 声道。
pub const PCM_CAP: usize = 2048 * 8;

type Handle = *mut std::ffi::c_void;
type OpenFn = unsafe extern "C" fn(i32, u32) -> Handle;
type CloseFn = unsafe extern "C" fn(Handle);
type FillFn = unsafe extern "C" fn(Handle, *mut *mut u8, *const u32, *mut u32) -> u32;
type DecodeFn = unsafe extern "C" fn(Handle, *mut i16, u32, u32) -> u32;
type StreamInfoFn = unsafe extern "C" fn(Handle) -> *const StreamInfo;

/// CStreamInfo 只声明用得到的前三个字段（v2.0.2 布局，对拍 bindings.rs）。
/// `sample_rate` 是含 SBR 的最终输出采样率；核心采样率在 aacSampleRate。
#[repr(C)]
struct StreamInfo {
    sample_rate: i32,
    frame_size: i32,
    num_channels: i32,
}

/// 解码一帧的结果。
pub enum Decoded {
    /// 出帧，PCM 已写入。
    Frame,
    /// 解码器内部缓冲已耗尽（外部数据全部消化），等下一批输入。
    NeedMore,
    /// 单帧损坏（0x4000 段），跳过本帧不断流。
    Conceal,
    /// 致命错误，附错误码。
    Fatal(u32),
}

/// 库的来源（日志用）。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Source {
    /// 插件自带的完整版（scripts/build-fdk-aac.sh 构建）。
    Bundled,
    /// 系统库（Debian/Ubuntu 是 free 版，须过 SBR 探针才可用）。
    System,
}

pub struct Lib {
    dl: *mut std::ffi::c_void,
    open: OpenFn,
    close: CloseFn,
    fill: FillFn,
    decode: DecodeFn,
    stream_info: StreamInfoFn,
    source: Source,
    origin: String,
}

// dl 句柄与函数指针加载后只读；Decoder 仅在解码线程内使用。
unsafe impl Send for Lib {}
unsafe impl Sync for Lib {}

impl Lib {
    /// 按优先级加载第一个 SBR 可用的库；失败时返回带安装指引的错误。
    pub fn acquire() -> Result<Arc<Lib>, String> {
        let mut candidates: Vec<(PathBuf, Source)> = Vec::new();
        // 1) 可执行文件旁的 lib/（自包含目录布局）
        if let Ok(exe) = std::env::current_exe() {
            if let Some(dir) = exe.parent() {
                candidates.push((dir.join("lib/libfdk-aac.so.2"), Source::Bundled));
            }
        }
        // 2) 插件安装位（开发迭代从 target 跑时走这里）
        let data_home = std::env::var_os("XDG_DATA_HOME")
            .map(PathBuf::from)
            .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".local/share")))
            .ok_or_else(|| "无法定位用户数据目录（HOME 未设置）".to_owned())?;
        candidates.push((
            data_home.join("yihu/plugins/radio/lib/libfdk-aac.so.2"),
            Source::Bundled,
        ));
        // 3) 系统 soname（free 版会被 SBR 探针拒掉）
        for name in ["libfdk-aac.so.2", "libfdk-aac.so.1", "libfdk-aac.so", "libfdk-aac.so.0"] {
            candidates.push((PathBuf::from(name), Source::System));
        }

        let mut saw_free = false;
        for (path, source) in candidates {
            let origin = path.display().to_string();
            let Some(lib) = try_load(&origin, source) else {
                continue;
            };
            let lib = Arc::new(lib);
            if lib.probe_sbr() {
                return Ok(lib);
            }
            saw_free = true;
            pwarn!("候选 libfdk-aac（{origin}）无 SBR 能力，跳过");
        }
        Err(if saw_free {
            "libfdk-aac 缺少 SBR 支持（Debian/Ubuntu 系统包 fdk-aac-free \
             剥除了 SBR/PS 解码器），无法播 HE-AAC 电台。\
             请运行 scripts/build-fdk-aac.sh 构建完整版"
                .to_owned()
        } else {
            let hint = yihu_core::distro::install_hint(&["libfdk-aac2"]);
            format!("缺少播放组件：libfdk-aac（{hint}；或运行 scripts/build-fdk-aac.sh 构建完整版）")
        })
    }

    /// SBR 能力探针：用真实 HE-AAD 帧解码，输出采样率须升到 44100。
    /// （free 版解出的是 22050 核心率，据此拒掉。）
    fn probe_sbr(&self) -> bool {
        let lib = Arc::new(Lib {
            dl: std::ptr::null_mut(), // 探针克隆体不拥有句柄，drop 不 close
            open: self.open,
            close: self.close,
            fill: self.fill,
            decode: self.decode,
            stream_info: self.stream_info,
            source: self.source,
            origin: self.origin.clone(),
        });
        let Some(mut dec) = Decoder::new(lib) else {
            return false;
        };
        let mut pcm = vec![0i16; PCM_CAP];
        let mut input: &[u8] = PROBE_FRAMES;
        let mut rate = 0;
        for _ in 0..16 {
            match dec.decode(&mut input, &mut pcm) {
                Decoded::Frame if dec.sample_rate > 24000 => return true,
                Decoded::Frame => rate = dec.sample_rate,
                Decoded::NeedMore if input.is_empty() => break,
                Decoded::NeedMore => {}
                Decoded::Conceal => {}
                Decoded::Fatal(_) => return false,
            }
        }
        pwarn!("SBR 探针未通过（输出 {rate}Hz）");
        false
    }
}

impl Drop for Lib {
    fn drop(&mut self) {
        if !self.dl.is_null() {
            unsafe { libc::dlclose(self.dl) };
        }
    }
}

fn try_load(origin: &str, source: Source) -> Option<Lib> {
    let Ok(c) = CString::new(origin) else { return None };
    let dl = unsafe { libc::dlopen(c.as_ptr(), libc::RTLD_NOW | libc::RTLD_LOCAL) };
    if dl.is_null() {
        return None;
    }
    let lib = Lib {
        dl,
        open: sym(dl, "aacDecoder_Open")?,
        close: sym(dl, "aacDecoder_Close")?,
        fill: sym(dl, "aacDecoder_Fill")?,
        decode: sym(dl, "aacDecoder_DecodeFrame")?,
        stream_info: sym(dl, "aacDecoder_GetStreamInfo")?,
        source,
        origin: origin.to_owned(),
    };
    Some(lib)
}

/// 缺符号也要 dlclose，不漏句柄。
fn sym<T>(dl: *mut std::ffi::c_void, name: &str) -> Option<T> {
    let c = CString::new(name).ok()?;
    let p = unsafe { libc::dlsym(dl, c.as_ptr()) };
    if p.is_null() {
        unsafe { libc::dlclose(dl) };
        None
    } else {
        // 函数指针与数据指针同宽（x86-64/aarch64）。
        Some(unsafe { std::mem::transmute_copy::<*mut std::ffi::c_void, T>(&p) })
    }
}

pub struct Decoder {
    lib: Arc<Lib>,
    handle: Handle,
    /// 输出规格（fdk 解出首帧才可知；SBR 下与 ADTS 头声明值不同）。
    pub sample_rate: u32,
    pub channels: u8,
    pub frame_size: usize,
    spec_changed: bool,
}

impl Decoder {
    pub fn new(lib: Arc<Lib>) -> Option<Self> {
        let handle = unsafe { (lib.open)(TT_MP4_ADTS, 1) };
        if handle.is_null() {
            return None;
        }
        Some(Self {
            lib,
            handle,
            sample_rate: 0,
            channels: 0,
            frame_size: 0,
            spec_changed: false,
        })
    }

    /// 喂入并尽量解码一帧。`input` 会被前移，消费掉已拷入解码器内部
    /// 缓冲的字节。**外部输入为空时也会继续消化内部缓冲**——fdk 的
    /// 运输缓冲（实测 32KB）远大于一帧，Fill 的消费领先于 Decode，
    /// 「外部输入吃完」不等于「解码器餍足」（2026-10-19 实测坑）。
    pub fn decode(&mut self, input: &mut &[u8], pcm: &mut [i16]) -> Decoded {
        debug_assert!(pcm.len() >= PCM_CAP);
        unsafe {
            if !input.is_empty() {
                let mut buf = [input.as_ptr() as *mut u8];
                let size = input.len() as u32;
                let mut valid = size;
                (self.lib.fill)(self.handle, buf.as_mut_ptr(), &size, &mut valid);
                *input = &input[(size - valid) as usize..];
            }

            let err = (self.lib.decode)(self.handle, pcm.as_mut_ptr(), pcm.len() as u32, 0);
            match err {
                AAC_DEC_OK => {
                    self.refresh_spec();
                    Decoded::Frame
                }
                e if e & 0xF000 == 0x1000 => Decoded::NeedMore,
                e if e & 0xF000 == 0x4000 => Decoded::Conceal,
                e => Decoded::Fatal(e),
            }
        }
    }

    /// 规格是否相对上次解码发生了变化（换台/中途自适应变更）。
    pub fn take_spec_changed(&mut self) -> bool {
        std::mem::replace(&mut self.spec_changed, false)
    }

    fn refresh_spec(&mut self) {
        let si = unsafe { (self.lib.stream_info)(self.handle) };
        if si.is_null() {
            return;
        }
        let (rate, ch, fs) = unsafe {
            (
                (*si).sample_rate.max(0) as u32,
                (*si).num_channels.clamp(0, 8) as u8,
                (*si).frame_size.max(0) as usize,
            )
        };
        if (rate, ch, fs) != (self.sample_rate, self.channels, self.frame_size) {
            self.spec_changed = true;
            self.sample_rate = rate;
            self.channels = ch;
            self.frame_size = fs;
        }
    }
}

impl Drop for Decoder {
    fn drop(&mut self) {
        unsafe { (self.lib.close)(self.handle) };
    }
}

